function auditMode(modeName) {
  console.log(`\n--- Auditing live Express router stack under NODE_ENV=${modeName} ---`);
  const appInstance = loadAppInEnv(modeName);
  const liveRoutes = getExpressRoutes(appInstance);

  console.log(`[${modeName}] Discovered ${liveRoutes.length} active Express routes.`);

  const liveRouteSet = new Set(liveRoutes.map((r) => `${r.method} ${r.path}`));
  const unregisteredRoutes = [];
  const missingCoverage = [];

  // 1. DIRECTION 1: Every live Express route MUST exist in registry with valid metadata
  for (const r of liveRoutes) {
    const key = `${r.method} ${r.path}`;
    const decl = ROUTE_PERMISSIONS.get(key);

    if (!decl) {
      unregisteredRoutes.push(r);
    } else if (!decl.permission && !decl.publicReason && !decl.selfScoped) {
      missingCoverage.push(r);
    }
  }

  // 2. DIRECTION 2: Every entry in registry MUST match a live Express route (no orphans)
  const orphanRegistryEntries = [];
  for (const [key, decl] of ROUTE_PERMISSIONS.entries()) {
    if (modeName === 'production' && decl.testOnly) {
      continue; // Skip test-only routes when auditing production
    }
    if (!liveRouteSet.has(key)) {
      orphanRegistryEntries.push(key);
    }
  }

  let failed = false;

  if (unregisteredRoutes.length > 0) {
    console.error(`[AUDIT FAILED] Direction 1 failure: ${unregisteredRoutes.length} real Express route(s) are NOT in ROUTE_PERMISSIONS:`);
    unregisteredRoutes.forEach((r) => console.error(`  - ${r.method} ${r.path}`));
    failed = true;
  }

  if (missingCoverage.length > 0) {
    console.error(`[AUDIT FAILED] Direction 1 failure: ${missingCoverage.length} route(s) lack permission, publicReason, and selfScoped:`);
    missingCoverage.forEach((r) => console.error(`  - ${r.method} ${r.path}`));
    failed = true;
  }

  if (orphanRegistryEntries.length > 0) {
    console.error(`[AUDIT FAILED] Direction 2 failure: ${orphanRegistryEntries.length} ROUTE_PERMISSIONS entry(ies) do NOT exist in the real Express router stack:`);
    orphanRegistryEntries.forEach((k) => console.error(`  - ${k}`));
    failed = true;
  }

  if (failed) {
    process.exit(1);
  }

  console.log(`✓ [${modeName}] Bidirectional verification passed: 100% of ${liveRoutes.length} real Express routes mapped; 0 orphan registry entries.`);
  return { count: liveRoutes.length, routes: liveRoutes };
}

function runAudit() {
  console.log('================================================================');
  console.log('         RBAC ROUTE PERMISSION AUDIT (DERIVED FROM STACK)      ');
  console.log('================================================================');

  // 1. Audit under NODE_ENV=production
  const prodResult = auditMode('production');

  // 2. Audit under NODE_ENV=test
  const testResult = auditMode('test');

  console.log('\n----------------------------------------------------------------');
  console.log(`Audit Summary:`);
  console.log(`- Production Route Count: ${prodResult.count}`);
  console.log(`- Test Route Count:       ${testResult.count}`);
  console.log(`----------------------------------------------------------------\n`);

  if (prodResult.count !== 86) {
    console.error(`[AUDIT FAILED] Expected exactly 86 routes in production mode, got ${prodResult.count}`);
    process.exit(1);
  }

  if (testResult.count !== 87) {
    console.error(`[AUDIT FAILED] Expected exactly 87 routes in test mode, got ${testResult.count}`);
    process.exit(1);
  }

  // Auto-generate documentation based on the REAL production stack
  const apiDocPath = path.resolve(__dirname, '../../../docs/API_PERMISSIONS.md');
  fs.writeFileSync(apiDocPath, generateApiPermissionsDoc(prodResult.routes), 'utf-8');
  console.log(`✓ Successfully regenerated ${apiDocPath} from live Express stack`);

  const matrixDocPath = path.resolve(__dirname, '../../../docs/PERMISSION_MATRIX.md');
  fs.writeFileSync(matrixDocPath, generatePermissionMatrixDoc(), 'utf-8');
  console.log(`✓ Successfully regenerated ${matrixDocPath}`);

  console.log('\n[RBAC AUDIT PASSED] System permissions and route catalog are 100% verified bidirectionally.\n');
}

if (require.main === module) {
  runAudit();
}

